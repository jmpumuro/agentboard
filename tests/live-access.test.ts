import { expect, it } from 'vitest';
import { emptyState } from '../apps/api/src/db/store';
import { createBoard, type Auth } from '../apps/api/src/services/core';
import { liveAccess } from '../apps/api/src/services/live-access';
it('ends live access on logout, expiry, member removal, rotation, scope loss and board deletion', () => {
    const state = emptyState();
    const user = { id: 'u', name: 'Alex', email: 'a@example.com', role: 'owner' as const, createdAt: new Date().toISOString(), passwordHash: 'unused' };
    state.users.push(user);
    const auth: Auth = { actor: { kind: 'user', id: 'u', name: 'Alex' }, user, scopes: ['boards:read', 'boards:write'] };
    const board = createBoard(state, auth, 'Live');
    state.sessions.session = { userId: 'u', expires: Date.now() + 60000 };
    const identity = { sessionHash: 'session' };
    expect(liveAccess(state, identity, board.id)).toBeDefined();
    state.sessions.session.expires = 0;
    expect(liveAccess(state, identity, board.id)).toBeUndefined();
    state.sessions.session.expires = Date.now() + 60000;
    state.users = [];
    expect(liveAccess(state, identity, board.id)).toBeUndefined();
    state.users.push(user);
    delete state.sessions.session;
    expect(liveAccess(state, identity, board.id)).toBeUndefined();
    const agent: any = { id: 'a', name: 'Agent', keyHash: 'old', status: 'active', scopes: ['boards:read'], boardIds: null };
    state.agents.push(agent);
    expect(liveAccess(state, { keyHash: 'old' }, board.id)).toBeDefined();
    agent.keyHash = 'new';
    expect(liveAccess(state, { keyHash: 'old' }, board.id)).toBeUndefined();
    agent.scopes = [];
    expect(liveAccess(state, { keyHash: 'new' }, board.id)).toBeUndefined();
    agent.scopes = ['boards:read']; agent.boardIds = [];
    expect(liveAccess(state, { keyHash: 'new' }, board.id)).toBeUndefined();
    agent.boardIds = null; state.boards[board.id].board.deletedAt = new Date().toISOString();
    expect(liveAccess(state, { keyHash: 'new' }, board.id)).toBeUndefined();
});
