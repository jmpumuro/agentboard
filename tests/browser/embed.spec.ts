import { E2E_ORIGIN } from './environment';
import { test, expect } from '@playwright/test';
import { login } from './helpers';
test('describe a mockup, refine it in place, and keep sandbox frames safe and stable', async ({ page }, info) => {
    await login(page);
    const headers = { Origin: E2E_ORIGIN };
    const b = await (await page.request.post('/api/v1/boards', { headers, data: { title: 'Mockup flow ' + info.project.name } })).json();
    const agent = await (await page.request.post('/api/v1/agents', { headers, data: { name: 'Designer ' + info.project.name, harness: 'test', scopes: ['boards:read', 'boards:write'], capabilities: ['add', 'edit'] } })).json();
    await page.goto('/boards/' + b.id);
    await page.getByRole('button', { name: 'Design tool', exact: true }).click();
    await page.locator('.canvas').click({ position: { x: 80, y: 150 } });
    await page.getByLabel('Choose agent').selectOption(agent.agent.id);
    await page.getByLabel('Ask your agent').fill('A simple three-plan pricing page with green accents.');
    await page.getByRole('button', { name: 'Send message', exact: true }).click();
    await expect(page.locator('.element.embed')).toHaveCount(1, { timeout: 10000 });
    await expect(page.frameLocator('.element.embed iframe').getByRole('heading', { name: 'Three simple plans' })).toBeVisible();
    await page.getByRole('button', { name: 'Hide response' }).click();
    await page.getByRole('button', { name: 'Fit to content', exact: true }).click();
    await page.locator('.element.embed').dblclick();
    await page.getByLabel('Ask your agent').fill('Make the pricing clearer and shorten the headline.');
    await page.getByRole('button', { name: 'Send message', exact: true }).click();
    await expect(page.frameLocator('.element.embed iframe').getByRole('heading', { name: 'Refined pricing' })).toBeVisible({ timeout: 10000 });
    await expect(page.locator('.element.embed')).toHaveCount(1);
    await page.getByRole('button', { name: 'Hide response' }).click();
    let externalRequests = 0;
    await page.route('https://blocked-assets.example/**', route => { externalRequests++; return route.abort(); });
    const html = '<style>body{margin:0;background:rgb(235,245,225)}</style><h1>Sandbox test</h1><script>parent.__embedScriptRan=true</script><img src="https://blocked-assets.example/tracker.png">';
    // Exercise sandboxing through the shared service; ordinary users only describe designs.
    const snapshot = await (await page.request.get('/api/v1/boards/' + b.id + '/elements')).json();
    const embed = snapshot.elements.find((e: any) => e.type === 'embed');
    await page.request.post('/api/v1/boards/' + b.id + '/ops', { headers, data: { ops: [{ op: 'update', id: embed.id, ifVersion: embed.version, data: { html } }] } });
    await expect(page.frameLocator('.element.embed iframe').getByRole('heading', { name: 'Sandbox test' })).toBeVisible();
    expect(await page.evaluate(() => (window as any).__embedScriptRan)).toBeUndefined();
    expect(externalRequests).toBe(0);
    await expect(page.locator('.element.embed iframe')).toHaveAttribute('sandbox', '');
    await page.evaluate(() => { (window as any).__savedFrame = document.querySelector('.element.embed iframe'); });
    const card = page.locator('.element.embed');
    const rect = await card.boundingBox();
    await page.mouse.move(rect!.x + 20, rect!.y + 14);
    await page.mouse.down();
    await page.mouse.move(rect!.x + 50, rect!.y + 45, { steps: 5 });
    await page.mouse.up();
    expect(await page.evaluate(() => (window as any).__savedFrame === document.querySelector('.element.embed iframe'))).toBe(true);
    const handle = page.locator('.element.embed.selected .resize-handle');
    const box = await handle.boundingBox();
    await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2);
    await page.mouse.down();
    await page.mouse.move(box!.x + 40, box!.y + 30, { steps: 5 });
    await page.mouse.up();
    expect(await page.evaluate(() => (window as any).__savedFrame === document.querySelector('.element.embed iframe'))).toBe(true);
});
