import { E2E_ORIGIN } from './environment';
import { test, expect } from '@playwright/test';
import { login } from './helpers';
test('build, explore and edit the same shared 3D parts through the toolbar', async ({ page }, info) => {
    await login(page);
    const headers = { Origin: E2E_ORIGIN };
    const board = await (await page.request.post('/api/v1/boards', { headers, data: { title: '3D flow ' + info.project.name } })).json();
    const agent = await (await page.request.post('/api/v1/agents', { headers, data: { name: '3D builder ' + info.project.name, harness: 'test', scopes: ['boards:read', 'boards:write'], capabilities: ['add', 'edit'] } })).json();
    await page.goto('/boards/' + board.id);
    await page.getByRole('button', { name: '3D tool', exact: true }).click();
    await page.locator('.canvas').click({ position: { x: 100, y: 150 } });
    await expect(page.locator('.element.scene3d')).toHaveCount(1);
    await expect(page.getByLabel('Ask your agent')).toHaveAttribute('placeholder', 'Describe the 3D model to build, or what to change…');
    await expect(page.locator('dialog')).toHaveCount(0);
    await page.getByLabel('Choose agent').selectOption(agent.agent.id);
    await page.getByLabel('Ask your agent').fill('Build a 3D engine model with named parts that pull apart.');
    await page.getByRole('button', { name: 'Send message' }).click();
    await expect.poll(async () => { const snapshot = await (await page.request.get('/api/v1/boards/' + board.id + '/elements')).json(); return snapshot.elements[0]?.parts?.length; }).toBe(9);
    await page.getByRole('button', { name: 'Hide response' }).click();
    await expect(page.locator('.scene3d-live canvas')).toHaveCount(1);
    const read = async () => (await (await page.request.get('/api/v1/boards/' + board.id + '/elements')).json());
    const before = await read();
    await page.getByRole('button', { name: 'Pull apart model', exact: true }).click();
    await page.getByLabel('Pull apart', { exact: true }).fill('1');
    await page.getByRole('button', { name: 'Select model part', exact: true }).click();
    await page.getByLabel('Model part', { exact: true }).selectOption('piston');
    await expect(page.locator('.scene3d-caption')).toContainText('Piston');
    await page.getByRole('button', { name: 'Only this part', exact: true }).click();
    expect((await read()).seq).toBe(before.seq);
    await page.getByRole('button', { name: 'Show all parts', exact: true }).click();
    await page.getByRole('button', { name: 'Bigger', exact: true }).click();
    await expect.poll(async () => (await read()).elements[0].parts.find((p: any) => p.id === 'piston').v).toBe(2);
    await page.getByRole('button', { name: 'Undo (⌘Z)', exact: true }).click();
    await expect.poll(async () => (await read()).elements[0].parts.find((p: any) => p.id === 'piston').v).toBe(3);
    await page.reload();
    await expect(page.locator('.element.scene3d')).toHaveCount(1);
    await expect(page.getByRole('group', { name: /How an engine turns fuel into motion. Parts:/ })).toBeVisible();
});
