import { test, expect } from '@playwright/test';
import { E2E_ORIGIN } from './environment';
import { login } from './helpers';
test('real OpenAI creates and refines the Submit button, then builds a shared bicycle model', async ({ page }) => {
    test.skip(!process.env.E2E_REAL_MODEL, 'Requires the configured live provider.');
    await login(page);
    const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
    const headers = { Origin: E2E_ORIGIN };
    const board = await (await page.request.post('/api/v1/boards', { headers, data: { title: 'Live provider end-to-end' } })).json();
    const agent = await (await page.request.post('/api/v1/agents', { headers, data: { name: 'Live designer', harness: 'test', scopes: ['boards:read', 'boards:write'], capabilities: ['add', 'draw', 'edit', 'knowledge'] } })).json();
    await page.goto('/boards/' + board.id);
    const canvas = page.locator('.canvas');
    const snapshot = async () => (await (await page.request.get('/api/v1/boards/' + board.id + '/elements')).json());
    async function ask(message: string) {
        await page.getByLabel('Choose agent').selectOption(agent.agent.id);
        await page.getByLabel('Ask your agent').fill(message);
        await page.getByRole('button', { name: 'Send message', exact: true }).click();
        let run: any;
        await expect.poll(async () => { const result = await (await page.request.get('/api/v1/boards/' + board.id + '/runs')).json(); run = result.items[0]; return ['done', 'failed', 'cancelled'].includes(run?.status); }, { timeout: 180000, intervals: [500, 1000] }).toBe(true);
        expect(run.status, JSON.stringify({ error: run.error, steps: run.steps })).toBe('done');
        expect(run.batches.length).toBeGreaterThan(0);
        expect(run.steps.filter((s: any) => s.status === 'failed'), JSON.stringify(run.steps)).toEqual([]);
        return run;
    }
    await page.getByRole('button', { name: 'Design tool', exact: true }).click();
    await canvas.click({ position: { x: 110, y: 180 } });
    await ask('Create one red round corner button with Submit text. Use an actual HTML button with a red background, white text and border-radius 12px.');
    await expect(page.locator('.element.embed')).toHaveCount(1);
    const embed = (await snapshot()).elements.find((e: any) => e.type === 'embed');
    const button = page.frameLocator('.element.embed iframe').getByRole('button', { name: 'Submit', exact: true });
    await expect(button).toBeVisible();
    const style = await button.evaluate(el => { const s = getComputedStyle(el); return { radius: s.borderRadius, color: s.backgroundColor }; });
    expect(parseFloat(style.radius)).toBeGreaterThan(0); const rgb = style.color.match(/\d+/g)!.map(Number); expect(rgb[0]).toBeGreaterThan(rgb[1]); expect(rgb[0]).toBeGreaterThan(rgb[2]);
    await ask('Change that same Submit button to blue. Keep one mockup, the same button text and rounded corners.');
    expect((await snapshot()).elements.filter((e: any) => e.type === 'embed').map((e: any) => e.id)).toEqual([embed.id]);
    const blue = await button.evaluate(el => getComputedStyle(el).backgroundColor); const channels = blue.match(/\d+/g)!.map(Number); expect(channels[2]).toBeGreaterThan(channels[0]);
    await page.getByRole('button', { name: 'Return to tools', exact: true }).click();
    if (await page.getByRole('button', { name: 'Hide response' }).isVisible()) await page.getByRole('button', { name: 'Hide response' }).click();
    await page.getByRole('button', { name: '3D tool', exact: true }).click();
    await canvas.click({ position: { x: 550, y: 200 } });
    await ask('Build a recognisable 3D bicycle and explain how the chain drives the rear wheel. Use the existing starter part as one bicycle part, add named explained parts and explicit out offsets so the breakdown reveals the drive system. Keep fewer than 20 parts.');
    const model = (await snapshot()).elements.find((e: any) => e.type === 'scene3d');
    expect(model.parts.length).toBeGreaterThan(4); expect(model.parts.every((p: any) => p.name && p.info && p.out)).toBe(true); expect(model.parts.map((p: any) => p.name + ' ' + p.info).join(' ')).toMatch(/chain/i);
    await ask('Connect the Submit button mockup to the bicycle model with one labelled board arrow, from the mockup to the model. Do not change their HTML or parts.');
    const connected = (await snapshot()).elements.filter((e: any) => e.type === 'arrow');
    expect(connected).toHaveLength(1); expect(connected[0]).toMatchObject({ from: embed.id, to: model.id });
    if (await page.getByRole('button', { name: 'Hide response' }).isVisible()) await page.getByRole('button', { name: 'Hide response' }).click();
    await page.getByRole('button', { name: 'Pull apart model', exact: true }).click(); await page.getByLabel('Pull apart', { exact: true }).fill('1');
    await expect(page.locator('.scene3d-live canvas')).toHaveCount(1);
    await page.screenshot({ path: 'reports/e2e-live-bicycle.png' });
    await page.reload(); await expect(page.locator('.element.scene3d')).toHaveCount(1); await expect(page.locator('.element.embed')).toHaveCount(1);
    expect(errors).toEqual([]);
});
