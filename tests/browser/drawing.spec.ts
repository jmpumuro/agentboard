import { E2E_ORIGIN } from './environment';
import { test, expect, type Page } from '@playwright/test';
import { login } from './helpers';
async function stroke(page: Page, x: number, y: number) { await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + 60, y + 20, { steps: 8 }); await page.mouse.move(x + 80, y + 70, { steps: 8 }); await page.mouse.up(); }
test('drawing parity, durable toolbar responses, abilities and theme grids', async ({ page }, info) => {
    await login(page);
    const base = E2E_ORIGIN, headers = { Origin: base };
    const b = await (await page.request.post(base + '/api/v1/boards', { headers, data: { title: 'Drawing flow ' + info.project.name } })).json();
    const agent = await (await page.request.post(base + '/api/v1/agents', { headers, data: { name: 'Drawing fixture ' + info.project.name, harness: 'test', scopes: ['boards:read', 'boards:write'], capabilities: ['add', 'draw', 'edit', 'knowledge'] } })).json();
    // Back remains actionable while a new board title is focused.
    await page.getByRole('button', { name: 'New board', exact: true }).click();
    await page.getByLabel('Board title').fill('Saved before Back');
    await page.getByRole('button', { name: 'Back to boards', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'A place to think together.' })).toBeVisible();
    await page.goto('/boards/' + b.id);
    await expect(page.locator('.canvas')).toBeVisible();
    const area = await page.locator('.canvas').boundingBox();
    const x = area!.x + 80, y = area!.y + 140;
    await page.getByRole('button', { name: 'Draw tool', exact: true }).click();
    await stroke(page, x, y);
    await expect(page.locator('.element.drawing')).toHaveCount(1);
    await stroke(page, x + 35, y + 80);
    await expect(page.locator('.element.drawing polyline')).toHaveCount(2);
    await page.getByRole('button', { name: 'Undo (⌘Z)' }).click();
    await expect(page.locator('.element.drawing polyline')).toHaveCount(1);
    await page.getByRole('button', { name: 'Draw tool', exact: true }).click();
    await stroke(page, x + 110, y);
    await expect(page.locator('.element.drawing')).toHaveCount(2);
    await page.getByRole('button', { name: 'Select tool', exact: true }).click();
    await page.locator('.element.drawing').last().click();
    await page.getByRole('button', { name: 'Describe drawing' }).click();
    await page.getByLabel('Description', { exact: true }).fill('A freehand corner');
    await page.getByRole('button', { name: 'Save description' }).click();
    await expect(page.getByRole('img', { name: 'A freehand corner' })).toBeVisible();
    const handle = page.locator('.element.drawing.selected .resize-handle');
    const resize = await handle.boundingBox();
    await page.mouse.move(resize!.x + resize!.width / 2, resize!.y + resize!.height / 2);
    await page.mouse.down();
    await page.mouse.move(resize!.x + 40, resize!.y + 40, { steps: 5 });
    await page.mouse.up();
    await page.getByRole('button', { name: 'Delete selected elements' }).click();
    await expect(page.locator('.element.drawing')).toHaveCount(1);
    await page.getByRole('button', { name: 'Undo (⌘Z)' }).click();
    await expect(page.locator('.element.drawing')).toHaveCount(2);
    const grip = page.getByRole('button', { name: 'Move toolbar' });
    const pos = await grip.boundingBox();
    await page.mouse.move(pos!.x + 10, pos!.y + 10);
    await page.mouse.down();
    await page.mouse.move(pos!.x + 10, pos!.y - 100, { steps: 8 });
    await page.mouse.up();
    const dock = await page.locator('.board-dock').boundingBox();
    await page.reload();
    await expect(page.locator('.board-dock')).toBeVisible();
    const restored = await page.locator('.board-dock').boundingBox();
    expect(Math.abs(restored!.y - dock!.y)).toBeLessThan(4);
    await page.getByRole('button', { name: 'Move toolbar' }).dblclick();
    await page.getByRole('button', { name: 'Ask an agent' }).click();
    await page.getByLabel('Choose agent').selectOption(agent.agent.id);
    await page.getByLabel('Ask your agent').fill('Draw a rocket');
    await page.getByRole('button', { name: 'Return to tools' }).click();
    await page.getByRole('button', { name: 'Ask an agent' }).click();
    await expect(page.getByLabel('Ask your agent')).toHaveValue('Draw a rocket');
    await page.getByRole('button', { name: 'Send message' }).click();
    await expect(page.getByRole('region', { name: 'Agent response' })).toContainText('I drew a test triangle in open space.', { timeout: 10000 });
    await expect(page.locator('.element.drawing')).toHaveCount(3);
    await page.reload();
    await expect(page.getByRole('region', { name: 'Agent response' })).toBeVisible();
    await page.getByRole('button', { name: 'Hide response' }).click();
    await page.reload();
    await expect(page.locator('.response-card')).toHaveCount(0);
    await page.getByRole('button', { name: 'Ask an agent' }).click();
    await page.getByRole('button', { name: 'Show the last response' }).click();
    await expect(page.locator('.response-card')).toBeVisible();
    await page.goto('/agents');
    await page.getByRole('button', { name: 'Edit ' + agent.agent.name, exact: true }).click();
    await page.locator('input[name="capabilities"][value="draw"]').uncheck();
    await page.getByRole('button', { name: 'Save changes' }).click();
    await page.goto('/boards/' + b.id);
    await page.getByRole('button', { name: 'Ask an agent' }).click();
    await page.getByLabel('Choose agent').selectOption(agent.agent.id);
    await page.getByLabel('Ask your agent').fill('Draw a rocket');
    await page.getByRole('button', { name: 'Send message' }).click();
    await expect(page.locator('.response-card')).toContainText('draw ability is disabled', { timeout: 10000 });
    await expect(page.locator('.element.drawing')).toHaveCount(3);
    await expect(page.locator('.response-pager')).toContainText('2 / 2');
    await page.getByRole('button', { name: 'Previous response' }).click();
    await expect(page.locator('.response-pager')).toContainText('1 / 2');
    for (const theme of ['light', 'dark']) {
        await page.evaluate(theme => { localStorage.setItem('agentboard.theme', theme); }, theme);
        await page.reload();
        for (const target of [100, 50, 200]) {
            const current = Number((await page.locator('.zoom-level').textContent())!.replace('%', ''));
            const button = page.getByRole('button', { name: target > current ? 'Zoom in' : 'Zoom out', exact: true });
            for (let n = 0; n < Math.round(Math.abs(target - current) / 10); n++)
                await button.click();
            await expect(page.locator('.canvas')).toHaveCSS('background-image', /radial-gradient/);
            await page.screenshot({ path: info.outputPath(`dots-${theme}-${target}.png`) });
        }
    }
});
